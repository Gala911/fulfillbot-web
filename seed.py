def seed():
    init_db()
    for company in COMPANIES:
        existing = get_company_by_name(company["name"])
        if existing:
            company_id = existing["id"]
        else:
            company_id = add_company(
                name=company["name"],
                website=company.get("website"),
                city=company.get("city"),
            )
        for service_type, (price, unit, comment) in company.get("tariffs", {}).items():
            set_tariff(company_id, service_type, price=price, unit=unit, comment=comment)
    print("База заполнена начальными данными: {} компаний.".format(len(COMPANIES)))


def seed_extra():
    """
    Добавляет компании без тарифов (найдены через каталог full-full.ru),
    не трогая уже существующие записи. Безопасно вызывать при каждом
    запуске сервера — уже добавленные компании просто пропускаются.
    """
    init_db()
    added = 0
    for company in EXTRA_COMPANIES:
        if get_company_by_name(company["name"]):
            continue
        add_company(
            name=company["name"],
            website=company.get("website"),
            city=company.get("city"),
            notes=company.get("notes"),
        )
        added += 1
    if added:
        print("Добавлено {} новых компаний без тарифов (для контактов).".format(added))


if __name__ == "__main__":
    seed()
    seed_extra()