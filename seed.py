def seed():
    init_db()
    for company in COMPANIES:
        existing = get_company_by_name(company["name"])
        if existing:
            company_id = existing["id"]
            if company.get("notes") or company.get("website") or company.get("city"):
                update_company_details(
                    company_id,
                    website=company.get("website") or existing["website"],
                    city=company.get("city") or existing["city"],
                    notes=company.get("notes"),
                )
        else:
            company_id = add_company(
                name=company["name"],
                website=company.get("website"),
                city=company.get("city"),
                notes=company.get("notes"),
            )
        for service_type, (price, unit, comment) in company.get("tariffs", {}).items():
            set_tariff(company_id, service_type, price=price, unit=unit, comment=comment)
    print("База заполнена начальными данными: {} компаний.".format(len(COMPANIES)))


def seed_extra():
    """
    Добавляет компании из EXTRA_COMPANIES, которых ещё нет в базе, и
    обновляет тарифы/заметки/статус у уже существующих — так что если
    в этом списке поправить цифры (например, пришла более точная
    котировка от компании), изменения подхватятся и на уже работающем
    сайте при следующем деплое. Название компании не меняется у
    существующих записей — сравнение идёт по нему, так что оно должно
    оставаться прежним, если это обновление, а не новая компания.
    """
    init_db()
    added = 0
    updated = 0
    for company in EXTRA_COMPANIES:
        existing = get_company_by_name(company["name"])
        if existing:
            company_id = existing["id"]
            update_company_details(
                company_id,
                website=company.get("website") or existing["website"],
                city=company.get("city") or existing["city"],
                notes=company.get("notes"),
            )
            updated += 1
        else:
            company_id = add_company(
                name=company["name"],
                website=company.get("website"),
                city=company.get("city"),
                notes=company.get("notes"),
            )
            added += 1
        if company.get("partner_status"):
            set_partner_status(company_id, company["partner_status"])
        for service_type, (price, unit, comment) in company.get("tariffs", {}).items():
            set_tariff(company_id, service_type, price=price, unit=unit, comment=comment)
    if added:
        print("Добавлено {} новых компаний.".format(added))
    if updated:
        print("Проверено/обновлено {} существующих компаний из списка EXTRA_COMPANIES.".format(updated))


if __name__ == "__main__":
    seed()
    seed_extra()